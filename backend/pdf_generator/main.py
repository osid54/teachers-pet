from reportlab.pdfgen import canvas
from reportlab.lib.pagesizes import letter
from reportlab.lib.units import inch
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, PageBreak, Table, TableStyle
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib import colors
import io

def create_pdf_worksheet(sections, answer_key_mode):
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=letter,
                            rightMargin=0.5*inch, leftMargin=0.5*inch,
                            topMargin=1.2*inch, bottomMargin=0.75*inch)
    styles = getSampleStyleSheet()
    story = []

    all_problems_for_answer_key = []
    def my_header_footer(canvas, doc):
        canvas.saveState()
        canvas.setFont('Helvetica-Bold', 10)
        canvas.drawString(0.5*inch, 10.5*inch, "TEACHER'S PET")

        canvas.setFont('Helvetica', 12)
        canvas.drawString(4.5*inch, 10.5*inch, "Name: ________________________")
        canvas.drawString(4.5*inch, 10.2*inch, "Date:  ________________________")

        canvas.setFont('Helvetica-Oblique', 8)
        canvas.drawCentredString(4.25*inch, 0.5*inch, f"Page {doc.page} - Generated by Teacher's Pet")
        canvas.restoreState()

    def make_vertical_problem(item, number, inline_answer):
        num1 = item.get('num1')
        num2 = item.get('num2')
        symbol = item.get('symbol', '+')

        if num1 is None or num2 is None:
            return Paragraph(f"{number}. {item.get('question', '')}", styles['Normal'])

        def format_val(value):
            return str(int(value)) if isinstance(value, float) and value.is_integer() else str(value)

        first_display = item.get('display_num1') or format_val(num1)
        second_display = item.get('display_num2') or format_val(num2)
        rows = [[f"{number}.", first_display], [symbol, second_display]]
        if inline_answer:
            rows.append(["=", item.get("display_answer") or str(item.get("answer", ""))])
        problem_table = Table(rows, colWidths=[0.3*inch, 0.8*inch])
        style_commands = [
            ('ALIGN', (1, 0), (1, -1), 'RIGHT'),
            ('FONTNAME', (1, 0), (1, -1), 'Courier-Bold'),
            ('FONTSIZE', (0, 0), (-1, -1), 14),
            ('LINEBELOW', (1, 1), (1, 1), 1.5, colors.black),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
            ('TOPPADDING', (0, 0), (-1, -1), 2),
        ]
        if inline_answer:
            style_commands.append(('LINEBELOW', (1, 2), (1, 2), 0.5, colors.lightgrey))
        problem_table.setStyle(TableStyle(style_commands))
        return problem_table

    problem_counter = 0
    problems_per_row = 5
    has_rendered_page = False

    for section in sections:
        page_count = section.get("page_count", 1)
        problems_per_page = section.get("problems_per_page", 10)
        pages = section.get("pages", [])
        topic_names = ", ".join(topic.get("topic_id", "").title() for topic in section.get("topics", []))
        section_title = "Mixed: " + topic_names if section.get("mode") == "mixed" else topic_names

        for page_index in range(page_count):
            if has_rendered_page:
                story.append(PageBreak())
            has_rendered_page = True

            section_number = section.get("section_number", 1)
            story.append(Paragraph(f"Section {section_number}: {section_title} (Page {page_index + 1} of {page_count})", styles['h1']))
            story.append(Spacer(1, 0.2 * inch))

            page_problems = pages[page_index] if page_index < len(pages) else []
            if len(page_problems) != problems_per_page:
                raise ValueError(f"Section {section_number} page {page_index + 1} has "
                                 f"{len(page_problems)} problems; expected {problems_per_page}.")
            for row_start in range(0, len(page_problems), problems_per_row):
                cells = []
                for item in page_problems[row_start:row_start + problems_per_row]:
                    problem_counter += 1
                    all_problems_for_answer_key.append(item)
                    cells.append(make_vertical_problem(item, problem_counter, answer_key_mode == "inline"))
                while len(cells) < problems_per_row:
                    cells.append(Paragraph("", styles['Normal']))
                story.append(Table([cells], colWidths=[1.5 * inch] * problems_per_row))
                story.append(Spacer(1, 0.05 * inch))

    if answer_key_mode == "separate" and all_problems_for_answer_key:
        story.append(PageBreak())
        story.append(Paragraph("Answer Key", styles['h2']))

        answer_data = []
        current_answer_row = []
        for index, problem in enumerate(all_problems_for_answer_key):
            answer = problem.get("display_answer") or problem.get('answer', 'N/A')
            current_answer_row.append(f"{index + 1}. {answer}")
            if len(current_answer_row) == 5:
                answer_data.append(current_answer_row)
                current_answer_row = []
        if current_answer_row:
            current_answer_row.extend([""] * (5 - len(current_answer_row)))
            answer_data.append(current_answer_row)

        story.append(Table(answer_data, colWidths=[1.5 * inch] * 5))

    doc.build(story, onFirstPage=my_header_footer, onLaterPages=my_header_footer)
    buffer.seek(0)
    return buffer